package install

import (
	"os"
	"strings"

	"github.com/LeikIsNRF/tt/internal/paths"
	"github.com/LeikIsNRF/tt/internal/tmux"
)

// Tab style keyed off the @tt_state window option the hook sets. Commas
// inside #{?...} branches must be escaped as #,.
const tabStyle = `#{?#{==:#{@tt_state},needs_you},#[bg=red#,fg=white#,bold],` +
	`#{?#{==:#{@tt_state},your_turn},#[bg=yellow#,fg=black],` +
	`#{?#{==:#{@tt_state},working},#[bg=colour22#,fg=white],}}}`

const needsYou = `#{?#{&&:#{@tt_needs_you},#{!=:#{@tt_needs_you},0}},` +
	`#[bg=red#,fg=white#,bold] #{@tt_needs_you} needs you #[default] ,}`

// tabFormat is tmux's default window format wrapped in tt's style.
const tabFormat = tabStyle + `#I:#W#{?window_flags,#{window_flags}, }#[default]`

// tmuxConf renders the snippet; exe is the absolute path of the tt binary.
func tmuxConf(exe string) string {
	return strings.Join([]string{
		"# Generated by `tt install` — overwritten on every install, don't edit.",
		"# Source it from ~/.tmux.conf:  source-file " + paths.TmuxConf(),
		"",
		"set -g @tt_conf 1",
		"set -go @tt_needs_you 0", // -o: re-sourcing must not reset a live count
		"",
		"set -g window-status-format '" + tabFormat + "'",
		"set -g window-status-current-format '" + tabFormat + "'",
		"set -g status-right '" + needsYou + `"#{=21:pane_title}" %H:%M %d-%b-%y'`,
		"set -g status-right-length 60",
		"",
		"# prefix t: the board as a popup (replaces the default clock-mode binding)",
		"bind-key t display-popup -E -w 90% -h 85% '" + exe + " --popup'",
		"# prefix T: capture a todo for this window's task (else the inbox).",
		"# -EE keeps the popup open if adding failed, so the error is readable.",
		"bind-key T display-popup -EE -w 70% -h 3 -T ' todo ' '" + exe + " add'",
		"",
	}, "\n")
}

func writeTmuxConf(exe string) error {
	if err := os.MkdirAll(paths.Home(), 0o755); err != nil {
		return err
	}
	return os.WriteFile(paths.TmuxConf(), []byte(tmuxConf(exe)), 0o644)
}

// TmuxConfLoaded reports whether the running tmux server has loaded it.
func TmuxConfLoaded() bool { return tmux.GlobalOption("@tt_conf") == "1" }

// TmuxConfSourced reports whether ~/.tmux.conf mentions tt's snippet.
func TmuxConfSourced() bool {
	b, err := os.ReadFile(paths.UserTmuxConf())
	return err == nil && strings.Contains(string(b), ".tt/tmux.conf")
}
